// Refreshes or verifies the offline currency snapshot against the API.
//
// Usage (from the mobile/ directory, with the Go API running):
//   dart run tool/currency_snapshot.dart --api http://localhost:8080          # rewrite
//   dart run tool/currency_snapshot.dart --api http://localhost:8080 --check  # verify
//
// The app reads `GET /currencies` at runtime for pickers; this snapshot only
// backs offline formatting (minor-unit exponents) and region suggestions.
// `--check` exits with 1 when the committed snapshot differs from the API.

import 'dart:convert';
import 'dart:io';

import 'gen_api.dart' show normalizeGenerated;

/// Snapshot location relative to the mobile/ package root.
const String snapshotPath = 'lib/core/formatting/currency_snapshot.dart';

Future<void> main(List<String> args) async {
  final bool check = args.contains('--check');
  final int apiIndex = args.indexOf('--api');
  final String api = apiIndex >= 0 && apiIndex + 1 < args.length
      ? args[apiIndex + 1]
      : 'http://localhost:8080';
  final Uri uri = Uri.parse('$api/api/v1/currencies');

  final List<Map<String, Object?>> currencies;
  try {
    currencies = await _fetch(uri);
  } on Exception catch (error) {
    stderr.writeln('Could not read $uri: $error');
    exitCode = 2;
    return;
  }
  final String source = renderSnapshot(currencies);
  final File file = File(snapshotPath);

  if (check) {
    final bool same =
        file.existsSync() &&
        normalizeGenerated(file.readAsStringSync()) ==
            normalizeGenerated(source);
    if (same) {
      stdout.writeln(
        '$snapshotPath matches $uri (${currencies.length} currencies).',
      );
    } else {
      stderr.writeln(
        '$snapshotPath differs from $uri. Run: '
        'dart run tool/currency_snapshot.dart --api $api',
      );
      exitCode = 1;
    }
    return;
  }

  await file.writeAsString(source);
  final ProcessResult format = await Process.run(
    Platform.resolvedExecutable,
    <String>['format', snapshotPath],
  );
  if (format.exitCode != 0) {
    stderr.writeln('dart format failed: ${format.stderr}');
    exitCode = format.exitCode;
    return;
  }
  stdout.writeln('Wrote $snapshotPath (${currencies.length} currencies).');
}

Future<List<Map<String, Object?>>> _fetch(Uri uri) async {
  final HttpClient client = HttpClient()
    ..connectionTimeout = const Duration(seconds: 10);
  try {
    final HttpClientRequest request = await client.getUrl(uri);
    request.headers
      ..set(HttpHeaders.acceptHeader, 'application/json')
      ..set('X-Client-Version', 'currency-snapshot-tool');
    final HttpClientResponse response = await request.close();
    final String body = await response.transform(utf8.decoder).join();
    if (response.statusCode != 200) {
      throw HttpException('HTTP ${response.statusCode}', uri: uri);
    }
    final Object? json = jsonDecode(body);
    if (json is! Map<String, Object?> || json['data'] is! List<Object?>) {
      throw const FormatException('Not a {data: [...]} envelope');
    }
    final List<Map<String, Object?>> list = <Map<String, Object?>>[
      for (final Object? item in json['data']! as List<Object?>)
        if (item is Map<String, Object?>) item,
    ];
    list.sort(
      (Map<String, Object?> a, Map<String, Object?> b) =>
          '${a['code']}'.compareTo('${b['code']}'),
    );
    return list;
  } finally {
    client.close(force: true);
  }
}

/// Dart source for the snapshot (deterministic; no timestamps).
String renderSnapshot(List<Map<String, Object?>> currencies) {
  final StringBuffer out = StringBuffer()
    ..writeln(
      '// GENERATED by tool/currency_snapshot.dart from GET /currencies.',
    )
    ..writeln('// Do not edit by hand. Refresh with:')
    ..writeln('//   dart run tool/currency_snapshot.dart --api <api origin>')
    ..writeln()
    ..writeln("import 'package:montra_mobile/core/api/generated/models.dart';")
    ..writeln()
    ..writeln('/// Offline snapshot of `GET /currencies`, sorted by code.')
    ..writeln('///')
    ..writeln(
      '/// The live endpoint stays authoritative: pickers use it, and the',
    )
    ..writeln(
      '/// server validates every code. The snapshot only backs offline',
    )
    ..writeln('/// formatting (minor-unit exponents) and region suggestions.')
    ..writeln('const List<CurrencyDto> currencySnapshot = <CurrencyDto>[');
  for (final Map<String, Object?> c in currencies) {
    final List<String> fields = <String>[
      'code: ${_literal('${c['code']}')}',
      'name: ${_literal('${c['name']}')}',
      'exponent: ${c['exponent']}',
      'selectable: ${c['selectable'] == true}',
      if (c['symbol'] is String) 'symbol: ${_literal(c['symbol']! as String)}',
      if (c['replaced_by'] is String)
        'replacedBy: ${_literal(c['replaced_by']! as String)}',
      if (c['retired_on'] is String)
        'retiredOn: ${_literal(c['retired_on']! as String)}',
    ];
    out.writeln('  CurrencyDto(${fields.join(', ')}),');
  }
  out.writeln('];');
  return out.toString();
}

String _literal(String value) {
  // Escape backslashes and `$` so the literal is not interpolated.
  final String escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n');
  if (!value.contains("'")) {
    return "'$escaped'";
  }
  if (!value.contains('"')) {
    return '"$escaped"';
  }
  return "'${escaped.replaceAll("'", r"\'")}'";
}
