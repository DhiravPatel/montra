// Meta is attached to every successful response (spec §6).
type Meta struct {
	RequestID  string    `json:"request_id" doc:"Correlation ID for support and logs"`
	Timestamp  time.Time `json:"timestamp" doc:"Server time the response was produced (RFC 3339)"`
	NextCursor string    `json:"next_cursor,omitempty" doc:"Opaque cursor for the next page; absent on the last page"`
	HasMore    *bool     `json:"has_more,omitempty" doc:"Whether more items exist after this page"`
}

// Envelope is the standard success body: {"data": ..., "meta": {...}}.
type Envelope[T any] struct {
	Data T    `json:"data" nullable:"false"`
	Meta Meta `json:"meta"`
}

// Response is a Huma output wrapping an Envelope body.
type Response[T any] struct {
	Body Envelope[T]
}

// NewMeta builds response metadata from the request context.
func NewMeta(ctx context.Context) Meta {
	return Meta{RequestID: logging.RequestID(ctx), Timestamp: time.Now().UTC()}
}

// OK wraps data in the standard envelope.
func OK[T any](ctx context.Context, data T) *Response[T] {
	return &Response[T]{Body: Envelope[T]{Data: nonNil(data), Meta: NewMeta(ctx)}}
}

// nonNil turns a nil slice into an empty one so list data is never null
// (the contract declares data as non-nullable).
func nonNil[T any](v T) T {
	rv := reflect.ValueOf(&v).Elem()
	if rv.Kind() == reflect.Slice && rv.IsNil() {
		rv.Set(reflect.MakeSlice(rv.Type(), 0, 0))
	}
	return v
}

// Page wraps a list page in the standard envelope with cursor metadata.
func Page[T any](ctx context.Context, items []T, nextCursor string) *Response[[]T] {
	if items == nil {
		items = []T{}
	}
	m := NewMeta(ctx)
	more := nextCursor != ""
	m.NextCursor = nextCursor
	m.HasMore = &more
	return &Response[[]T]{Body: Envelope[[]T]{Data: items, Meta: m}}
}

// Empty is the data payload for commands with no result.
type Empty struct {
	OK bool `json:"ok"`
}

// Done returns {"data": {"ok": true}}.
func Done(ctx context.Context) *Response[Empty] {
	return OK(ctx, Empty{OK: true})
}

// ErrorObject is the body of the standard error envelope.
type ErrorObject struct {
	Code      string          `json:"code" doc:"Stable machine-readable error code"`
	Message   string          `json:"message" doc:"Safe human-readable message"`
	Details   []apperr.Detail `json:"details" doc:"Field-level problems, may be empty"`
	RequestID string          `json:"request_id" doc:"Correlation ID"`
}

// TransformSchema publishes the closed error-code list as an enum.
func (ErrorObject) TransformSchema(_ huma.Registry, s *huma.Schema) *huma.Schema {
	if c, ok := s.Properties["code"]; ok {
		c.Enum = nil
		for _, code := range apperr.Codes() {
			c.Enum = append(c.Enum, string(code))
		}
	}
	return s
}

// ErrorResponse is the standard error body {"error": {...}}; it implements
// huma.StatusError so it can be returned from handlers and generated by the
// framework.
type ErrorResponse struct {
	status int
	Err    ErrorObject `json:"error"`
}

func (e *ErrorResponse) Error() string { return e.Err.Code + ": " + e.Err.Message }

// GetStatus implements huma.StatusError.
func (e *ErrorResponse) GetStatus() int { return e.status }

// ContentType implements huma.ContentTypeFilter (plain JSON, not problem+json).
func (e *ErrorResponse) ContentType(string) string { return "application/json" }

// Status returns the HTTP status code.
func (e *ErrorResponse) Status() int { return e.status }

// safeMessages are used for framework-originated errors so internal parser
// messages never reach clients.
var safeMessages = map[apperr.Code]string{
	apperr.CodeValidation:       "The request could not be processed.",
	apperr.CodeBadRequest:       "The request was malformed.",
	apperr.CodeUnauthenticated:  "Authentication is required.",
	apperr.CodeForbidden:        "You do not have permission to perform this action.",
	apperr.CodeNotFound:         "The requested resource was not found.",
	apperr.CodeConflict:         "The request conflicts with the current state.",
	apperr.CodePayloadTooLarge:  "The request body is too large.",
	apperr.CodeUnsupportedMedia: "The content type is not supported.",
	apperr.CodeRateLimited:      "Too many requests. Please wait and try again.",
	apperr.CodeTimeout:          "The request timed out.",
	apperr.CodeUnavailable:      "The service is temporarily unavailable.",
	apperr.CodeInternal:         "An unexpected error occurred.",
	apperr.CodeGone:             "This link has expired.",
}

// BuildError converts framework or service errors into the standard error
// response, logging internal causes without exposing them.
func BuildError(ctx context.Context, status int, msg string, errs ...error) *ErrorResponse {
	if ctx == nil {
		ctx = context.Background()
	}
	resp := &ErrorResponse{status: status}
	resp.Err.RequestID = logging.RequestID(ctx)
	resp.Err.Details = []apperr.Detail{}

	for _, err := range errs {
		if err == nil {
			continue
		}
		var ae *apperr.Error
		if errors.As(err, &ae) {
			resp.status = ae.Status
			resp.Err.Code = string(ae.Code)
			resp.Err.Message = ae.Message
			if len(ae.Details) > 0 {
				resp.Err.Details = ae.Details
			}
			if ae.Status >= 500 {
				slog.ErrorContext(ctx, "request failed", slog.String("code", string(ae.Code)), slog.Any("error", err))
			}
			return resp
		}
		var er *ErrorResponse
		if errors.As(err, &er) {
			return er
		}
	}

	code := apperr.CodeForStatus(status)
	resp.Err.Code = string(code)
	resp.Err.Message = safeMessages[code]
	if resp.Err.Message == "" {
		resp.Err.Message = "The request could not be processed."
	}
	for _, err := range errs {
		if err == nil {
			continue
		}
		var d huma.ErrorDetailer
		if errors.As(err, &d) {
			ed := d.ErrorDetail()
			resp.Err.Details = append(resp.Err.Details, schemaDetail(ed.Location, ed.Message))
		}
	}
	if status >= 500 {
		slog.ErrorContext(ctx, "request failed", slog.Int("status", status), slog.String("framework_message", msg), slog.Any("errors", errs))
	}
	return resp
}

// InstallHumaErrorModel replaces Huma's default problem+json error model
// with Montra's envelope. Must run before any operation is registered.
func InstallHumaErrorModel() {
	huma.NewError = func(status int, msg string, errs ...error) huma.StatusError {
		return BuildError(context.Background(), status, msg, errs...)
	}
	huma.NewErrorWithContext = func(hctx huma.Context, status int, msg string, errs ...error) huma.StatusError {
		ctx := context.Background()
		if hctx != nil {
			ctx = hctx.Context()
		}
		return BuildError(ctx, status, msg, errs...)
	}
}

// WriteError writes the standard error envelope from plain net/http code
// (middleware that runs before Huma).
func WriteError(w http.ResponseWriter, r *http.Request, err error) {
	ae := apperr.From(err)
	resp := BuildError(r.Context(), ae.Status, ae.Message, ae)
	w.Header().Set("Content-Type", "application/json")
	w.Header().Set("Cache-Control", "no-store")
	w.WriteHeader(resp.status)
	_ = json.NewEncoder(w).Encode(resp)
}

var cursorAEAD atomic.Pointer[cipher.AEAD]

// SetCursorKey makes pagination cursors opaque: positions (which can hold a
// row's date or amount) are encrypted and authenticated, so cursors reveal
// nothing in URLs or logs and cannot be forged. Called once at start-up.
func SetCursorKey(key []byte) {
	sum := sha256.Sum256(append([]byte("montra/cursor\x00"), key...))
	block, err := aes.NewCipher(sum[:])
	if err != nil {
		panic(err)
	}
	aead, err := cipher.NewGCM(block)
	if err != nil {
		panic(err)
	}
	cursorAEAD.Store(&aead)
}

// EncodeCursor produces an opaque cursor from a JSON-serializable position.
func EncodeCursor(v any) (string, error) {
	b, err := json.Marshal(v)
	if err != nil {
		return "", err
	}
	if p := cursorAEAD.Load(); p != nil {
		aead := *p
		nonce := make([]byte, aead.NonceSize())
		if _, err := rand.Read(nonce); err != nil {
			return "", err
		}
		b = aead.Seal(nonce, nonce, b, []byte("cursor"))
	}
	return base64.RawURLEncoding.EncodeToString(b), nil
}

// DecodeCursor parses an opaque cursor; invalid cursors are a client error.
func DecodeCursor(s string, v any) error {
	if s == "" {
		return nil
	}
	invalid := apperr.FieldError("query.cursor", "Invalid cursor. Start again from the first page.")
	b, err := base64.RawURLEncoding.DecodeString(s)
	if err != nil || len(b) > 2048 {
		return invalid
	}
	if p := cursorAEAD.Load(); p != nil {
		aead := *p
		if len(b) < aead.NonceSize() {
			return invalid
		}
		if b, err = aead.Open(nil, b[:aead.NonceSize()], b[aead.NonceSize():], []byte("cursor")); err != nil {
			return invalid
		}
	}
	if err := json.Unmarshal(b, v); err != nil {
		return invalid
	}
	return nil
}

// IdemHeader is embedded in inputs of financial writes (spec §6): retries
// with the same key return the original result.
type IdemHeader struct {
	Key string `header:"Idempotency-Key" required:"true" minLength:"8" maxLength:"128" doc:"Client-generated unique key; retries return the original result"`
}

// ReplayOutput is a success envelope that marks idempotent replays.
type ReplayOutput[T any] struct {
	Replayed string `header:"Idempotent-Replayed"`
	Body     Envelope[T]
}

// Replay builds a ReplayOutput.
func Replay[T any](ctx context.Context, v T, replayed bool) *ReplayOutput[T] {
	o := &ReplayOutput[T]{Body: Envelope[T]{Data: nonNil(v), Meta: NewMeta(ctx)}}
	if replayed {
		o.Replayed = "true"
	}
	return o
}
